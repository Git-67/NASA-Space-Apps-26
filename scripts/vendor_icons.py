"""Copy the icons the site uses into the repository, as SVG paths.

Icons: Google's Material Symbols, Outlined, weight 400 (Apache License 2.0),
       one 24px SVG per icon from Google Fonts.
Output: src/components/ui/icon-paths.js (generated; do not edit), read by
        src/components/ui/icon.js, which draws each icon as an inline SVG.

Why SVG and not the icon font: a ligature font shows the icon's name as
plain text whenever the font is missing, slow, or an older cached copy
without that icon (which happened on 14 Nov 2026). Inline SVG has no font to
load, works offline, and can never show as words.

Run:  python3 scripts/vendor_icons.py   (after using a new icon, add it to ICON_NAMES)
"""
from __future__ import annotations

import json
import re
import urllib.request

from mars_data import REPO_ROOT

OUTPUT_FILE = REPO_ROOT / "src" / "components" / "ui" / "icon-paths.js"
SVG_URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/{name}/default/24px.svg"
# Every icon the page uses, the Weather tab's included.
ICON_NAMES = [
    "add_location", "air", "arrow_downward", "arrow_forward", "arrow_upward", "blur_on", "calendar_month",
    "check_box_outline_blank", "check_circle", "chevron_right", "close", "close_fullscreen", "cloud", "compress",
    "cyclone", "dashboard", "directions_walk", "error", "event", "fast_forward", "filter_b_and_w", "flag",
    "flare", "grain", "grid_on", "height", "help", "info", "label", "landscape", "layers", "light_mode", "my_location",
    "open_in_full", "palette", "partly_cloudy_day", "pause", "play_arrow", "refresh", "scatter_plot", "schedule",
    "show_chart", "star", "storm", "table_chart", "thermostat", "today", "trending_down", "trending_flat",
    "trending_up", "visibility", "warning", "water_drop", "wb_twilight",
]
VIEW_BOX = "0 -960 960 960"
PATH = re.compile(r'<path d="([^"]+)"')
_USER_AGENT = "Mozilla/5.0 (compatible; data-preparation-script)"


def fetch_path(name: str) -> str:
    """The single path of one icon's SVG."""
    request = urllib.request.Request(SVG_URL.format(name=name), headers={"User-Agent": _USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        svg = response.read().decode()
    if f'viewBox="{VIEW_BOX}"' not in svg:
        raise ValueError(f"{name}: unexpected viewBox")
    paths = PATH.findall(svg)
    if len(paths) != 1:
        raise ValueError(f"{name}: expected one path, found {len(paths)}")
    return paths[0]


def main() -> None:
    paths = {name: fetch_path(name) for name in sorted(ICON_NAMES)}
    OUTPUT_FILE.write_text(
        "// @ts-check\n"
        "// GENERATED by scripts/vendor_icons.py. Do not edit by hand.\n"
        "// Material Symbols Outlined (Apache License 2.0), Google. One SVG path per icon.\n\n"
        f"/** viewBox shared by every icon. */\nexport const ICON_VIEW_BOX = '{VIEW_BOX}';\n\n"
        "/** @type {Record<string, string>} */\n"
        f"export const ICON_PATHS = {json.dumps(paths, indent=2)};\n",
        encoding="utf-8",
    )
    size = OUTPUT_FILE.stat().st_size
    print(f"Wrote {OUTPUT_FILE.relative_to(REPO_ROOT)}: {len(paths)} icons, {size / 1024:.1f} KB")


if __name__ == "__main__":
    main()
