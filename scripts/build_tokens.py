"""Generate src/styles/tokens.css from the front matter of DESIGN.md.

DESIGN.md is the single source of truth for colours, type, radius and spacing.
Never edit tokens.css by hand: change DESIGN.md, then run this script.

Colour tokens whose name starts with "light-" become overrides of the token
with the same name minus that prefix, applied when the light theme is active.

Run:  python3 scripts/build_tokens.py   (needs PyYAML, see requirements.txt)
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DESIGN_FILE = REPO_ROOT / "DESIGN.md"
OUTPUT_FILE = REPO_ROOT / "src" / "styles" / "tokens.css"
LIGHT_PREFIX = "light-"

# Fallback stacks from the "Font families" section of DESIGN.md.
FONT_STACKS = {
    "Space Grotesk": '"Space Grotesk", "Inter", system-ui, sans-serif',
    "Inter": '"Inter", system-ui, -apple-system, "Segoe UI", sans-serif',
    "JetBrains Mono": '"JetBrains Mono", ui-monospace, "SF Mono", Menlo, monospace',
}


def declarations(tokens: dict[str, Any]) -> tuple[list[str], list[str]]:
    """Build the CSS declarations for the default (dark) theme and the light overrides."""
    base: list[str] = []
    light: list[str] = []
    for name, value in tokens["colors"].items():
        if name.startswith(LIGHT_PREFIX):
            light.append(f"--color-{name.removeprefix(LIGHT_PREFIX)}: {value};")
        else:
            base.append(f"--color-{name}: {value};")
    for name, value in tokens["rounded"].items():
        base.append(f"--radius-{name}: {value};")
    for name, value in tokens["spacing"].items():
        base.append(f"--space-{name}: {value};")
    for name, spec in tokens["typography"].items():
        stack = FONT_STACKS[spec["fontFamily"]]
        base.append(f"--type-{name}: {spec['fontWeight']} {spec['fontSize']}/{spec['lineHeight']} {stack};")
        base.append(f"--tracking-{name}: {spec.get('letterSpacing', '0')};")
    return base, light


def main() -> None:
    text = DESIGN_FILE.read_text(encoding="utf-8")
    tokens = yaml.safe_load(text.split("\n---\n")[0].removeprefix("---\n"))
    base, light = declarations(tokens)
    indent = "\n  "
    css = (
        "/* GENERATED by scripts/build_tokens.py from DESIGN.md. Do not edit by hand. */\n\n"
        "/* Dark theme: the default. */\n"
        f":root {{{indent}color-scheme: dark;{indent}{indent.join(base)}\n}}\n\n"
        "/* Light theme, when the visitor chose it with the toggle. */\n"
        f':root[data-theme="light"] {{{indent}color-scheme: light;{indent}{indent.join(light)}\n}}\n\n'
        "/* Light theme, when the system asks for it and the visitor has not chosen dark. */\n"
        "@media (prefers-color-scheme: light) {\n"
        f'  :root:not([data-theme="dark"]) {{{indent}  color-scheme: light;{indent}  {(indent + "  ").join(light)}\n  }}\n}}\n'
    )
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(css, encoding="utf-8")
    print(f"Wrote {OUTPUT_FILE.relative_to(REPO_ROOT)}: {len(base)} tokens, {len(light)} light overrides")


if __name__ == "__main__":
    main()
